import { test, expect } from '@playwright/test';

test('dashboard filters, chart modes, empty state, retry and mobile layout', async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.text().includes('Content Security Policy')) errors.push(message.text()); });
  await page.addInitScript(() => sessionStorage.setItem('desenrola.token', 'dashboard-test'));
  await page.route('**/api/auth/me', route => route.fulfill({ json: { name: 'Ana', email: 'ana@example.com' } }));
  let fail = false;
  const requests = [];
  await page.route('**/api/transactions/dashboard?*', route => {
    const query = new URL(route.request().url()).searchParams;
    requests.push(Object.fromEntries(query));
    if (fail) return route.fulfill({ status: 503, json: { message: 'Banco indisponível.' } });
    const empty = query.get('date') === '2026-09-01';
    const daily = [{ date: '2026-10-13', income: empty ? '0.00' : '100.30', expense: empty ? '0.00' : '150.10', balance: empty ? '0.00' : '-49.80' }];
    return route.fulfill({ json: { from: daily[0].date, to: daily[0].date, ...daily[0], daily } });
  });
  await page.goto('/#/dashboard');
  await expect(page.locator('.balance strong')).toContainText(/-R\$\s*49,80/);
  await expect(page.getByRole('heading', { name: 'Entradas versus saídas por dia' })).toBeVisible();
  expect(requests.at(-1).period).toBe('month');
  expect(await page.locator('.chart-bar.expense').evaluate(bar => bar.getBoundingClientRect().height)).toBeGreaterThan(100);
  await page.getByLabel('Período', { exact: true }).selectOption('week');
  await page.getByLabel('Data de referência').fill('2026-10-13');
  await page.getByRole('button', { name: 'Aplicar filtro' }).click();
  await expect(page.locator('.balance strong')).toContainText(/-R\$\s*49,80/);
  expect(requests.at(-1)).toEqual({ period: 'week', date: '2026-10-13' });
  await page.getByLabel('Visualização do gráfico').selectOption('income');
  await expect(page.getByRole('heading', { name: 'Entradas por dia', exact: true })).toBeVisible();
  await expect(page.locator('.chart-bar.expense')).toHaveCount(0);
  await page.getByLabel('Visualização do gráfico').selectOption('expense');
  await expect(page.getByRole('heading', { name: 'Saídas por dia', exact: true })).toBeVisible();
  await page.getByLabel('Período', { exact: true }).selectOption('day');
  await page.getByLabel('Data de referência').fill('2026-09-01');
  await page.getByRole('button', { name: 'Aplicar filtro' }).click();
  await expect(page.getByText('Sem valores de saídas neste período.')).toBeVisible();
  expect(requests.at(-1)).toEqual({ period: 'day', date: '2026-09-01' });
  fail = true;
  await page.getByRole('button', { name: 'Atualizar resumo' }).click();
  await expect(page.getByRole('alert')).toHaveText('Banco indisponível.');
  fail = false;
  await page.getByRole('button', { name: 'Tentar novamente' }).click();
  await expect(page.locator('.balance strong')).toContainText('0,00');
  await page.getByLabel('Data de referência').fill('2026-10-13');
  await page.getByRole('button', { name: 'Aplicar filtro' }).click();
  await expect(page.locator('.balance strong')).toContainText(/-R\$\s*49,80/);
  await page.getByLabel('Visualização do gráfico').selectOption('comparison');
  await page.screenshot({ path: 'test-results/dashboard-filter-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/dashboard-filter-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
